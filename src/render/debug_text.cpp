const std::uint8_t* debugGlyph(char character) {
    const char upper = char(std::toupper(static_cast<unsigned char>(character)));
    const Glyph* found = std::find_if(std::begin(kGlyphs), std::end(kGlyphs), [&](const Glyph& glyph) { return glyph.character == upper; });
    if (found == std::end(kGlyphs)) found = std::find_if(std::begin(kGlyphs), std::end(kGlyphs), [](const Glyph& glyph) { return glyph.character == '?'; });
    return found->rows;
}

DebugTextImage rasteriseDebugText(const std::vector<std::string>& lines, int scale) {
    std::size_t columns = 0;
    for (const std::string& line : lines) columns = std::max(columns, line.size());
    DebugTextImage image;
    image.width = scale * (2 * kDebugPadding + int(columns) * kDebugGlyphAdvance);
    image.height = scale * (2 * kDebugPadding + int(lines.size()) * kDebugLineAdvance);
    image.rgba.assign(std::size_t(image.width) * std::size_t(image.height) * 4, 0);
    for (std::size_t i = 0; i < image.rgba.size(); i += 4) {
        image.rgba[i] = image.rgba[i + 1] = image.rgba[i + 2] = 0;
        image.rgba[i + 3] = 170;
    }
    for (std::size_t row = 0; row < lines.size(); ++row)
        for (std::size_t column = 0; column < lines[row].size(); ++column) {
            const std::uint8_t* rows = debugGlyph(lines[row][column]);
            for (int y = 0; y < kDebugGlyphHeight; ++y)
                for (int x = 0; x < kDebugGlyphWidth; ++x) {
                    if (!(rows[y] >> (kDebugGlyphWidth - 1 - x) & 1)) continue;
                    const int left = scale * (kDebugPadding + int(column) * kDebugGlyphAdvance + x);
                    const int top = scale * (kDebugPadding + int(row) * kDebugLineAdvance + y);
                    for (int dy = 0; dy < scale; ++dy)
                        for (int dx = 0; dx < scale; ++dx) {
                            std::uint8_t* pixel = &image.rgba[(std::size_t(top + dy) * std::size_t(image.width) + std::size_t(left + dx)) * 4];
                            pixel[0] = pixel[1] = pixel[2] = pixel[3] = 255;
                        }
                }
        }
    return image;
}

