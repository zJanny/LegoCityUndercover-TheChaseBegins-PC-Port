int find(const chase::runtime::ClimbBarSet& set, const char* name) {
    for (std::size_t i = 0; i < set.bars.size(); ++i)
        if (set.bars[i].instance == name) return int(i);
    throw std::runtime_error(std::string("no bar ") + name);
}

chase::assets::Animation clip(chase::assets::FuseArchive& archive, const chase::runtime::CarryAnimations& table, int id) {
    using namespace chase;
    const assets::FuseEntry* entry = archive.find("models/char_minifig/class_generic/" + table.name(id) + "_minifig.bfnanm");
    require(entry != nullptr, "clip missing " + table.name(id));
    return assets::parseAnimation(archive.read(*entry));
}

// The floor of the ground probe range (groundContact: from 0.3 above the node down to 0.1 + reach below it).
std::function<std::optional<float>(const float[3], float)> floorAt(float height) {
    return [height](const float position[3], float reach) -> std::optional<float> {
        if (height <= position[1] + 0.3f && height >= position[1] - 0.1f - reach) return height;
        return std::nullopt;
    };
}

void replay(const chase::runtime::ClimbBarSet& set, const chase::runtime::AcrobatPoleClips& clips, chase::runtime::AcrobatPoleRider& rider,
            const Row* rows, std::size_t count, float floor, const std::string& name, const std::function<void(int)>& afterRow) {
    using namespace chase;
    float position[3] = {rows[0].x, rows[0].y, rows[0].z};
    std::int16_t facing = std::int16_t(std::lround(std::atan2(rows[0].fx, rows[0].fz) * kHeadingScale));
    for (std::size_t k = 1; k < count; ++k) {
        const Row& row = rows[k];
        runtime::AcrobatPoleInput input;
        input.dt = kDt;
        std::copy(position, position + 3, input.position);
        input.facing = facing;
        input.bHeld = (row.held & 2) != 0;
        input.stickHeld = (row.held & 1) != 0;
        input.stickHeading = std::int16_t(row.heading);
        input.cameraYaw = row.cameraYaw;
        input.ground = floorAt(floor);
        const runtime::AcrobatPoleStep step = runtime::acrobatPoleUpdate(rider, set, clips, input);
        const std::string where = name + " row " + std::to_string(row.frame);
        require((step.riding ? step.state : runtime::kAcrobatPoleFallState) == row.state, where + ": state " + std::to_string(step.state));
        std::copy(step.position, step.position + 3, position);
        facing = step.facing;
        require(near(position[0], row.x, 6e-4f) && near(position[1], row.y, 6e-4f) && near(position[2], row.z, 6e-4f),
                where + ": position " + std::to_string(position[0]) + " " + std::to_string(position[1]) + " " + std::to_string(position[2]));
        const float heading = float(std::uint16_t(facing)) / kHeadingScale;
        require(near(std::sin(heading), row.fx, 4e-4f) && near(std::cos(heading), row.fz, 4e-4f), where + ": facing");
        if (afterRow) afterRow(row.frame);
        if (!step.riding) return;
    }
}
