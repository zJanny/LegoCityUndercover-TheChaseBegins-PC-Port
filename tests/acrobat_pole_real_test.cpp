int main(int argc, char** argv) {
    if (argc != 3) {
        std::cerr << "usage: acrobat-pole-real-test FIB NAMES\n";
        return 2;
    }
    if (!std::filesystem::exists(argv[1]) || !std::filesystem::exists(argv[2])) {
        std::cout << "acrobat-pole-real-test: data not available, skipped\n";
        return 77;
    }
    try {
        using namespace chase;
        assets::FuseArchive archive(argv[1]);
        archive.loadNames(argv[2]);
        const assets::FuseEntry* entry = archive.find(kLevelFile);
        require(entry != nullptr, std::string("not in archive: ") + kLevelFile);
        const assets::Level level = assets::parseLevel(archive.read(*entry));
        const runtime::ClimbBarSet set = runtime::loadClimbBars(level, assets::archiveClassLookup(archive));
        const runtime::CarryAnimations table(assets::parseTable(archive.read(*archive.find("tables/tablesanimations.bxls"))));
        const runtime::AcrobatPoleClips clips =
            runtime::acrobatPoleClips(clip(archive, table, runtime::kAnimationAcrobatPoleIdle), clip(archive, table, runtime::kAnimationAcrobatPoleFlip),
                                      clip(archive, table, runtime::kAnimationAcrobatPoleJump));

        // Clip facts (docs/re/player-traversal-rails.md §2026-10-19T07:53:17): hpole_loop 33 frames at 30 per second, hpole_180 10 at 15, hpole_dismount 12 at 15
        // with the root extent z 4.53562; the track 0xc3fcea91 changes at key times 0.231413 and 0.922648; ta..tb = (0.922648 - 0.231413) x 12.
        require(clips.idle.length == 33.0f && clips.idle.rate == 30.0f && clips.flip.length == 10.0f && clips.flip.rate == 15.0f, "idle and flip clips");
        require(clips.jump.length == 12.0f && clips.jump.rate == 15.0f && near(clips.jumpTravel, 4.53562f, 1e-4f), "jump clip");
        require(clips.jumpEventFrames.size() == 2 && near(clips.jumpEventFrames[0], 2.77696f, 1e-4f) && near(clips.jumpEventFrames[1], 11.07178f, 1e-4f),
                "jump events");
        require(near(clips.jumpPhaseFrames, 8.29482f, 1e-4f), "jump phase span");

        const int pole01 = find(set, "1-2_flagpole_01");
        const int pole02 = find(set, "1-2_flagpole_02");
        require(set.bars[std::size_t(pole01)].links[0].objectType == runtime::kClimbBarObjectType, "PrimaryNextBar of 01 is a bar");
        require(set.bars[std::size_t(find(set, "1-2_flagpole_04"))].links[0].objectType == runtime::kPointObjectType, "the landing point is a point");

        // t1 from row 2: idle on 01 (state 93). Clip time 20 frames at the update of row 3: chosen so that the idle end (clip time 32) falls in row 15, where t1
        // requests 95; the user state's clip time is not recorded. ctrl+0x2e4 after the enters: 4.90156 (0x409cd98a, row 40) and -15.6937 (0xc17b1943, row 88); the
        // floor at the landing 37.03597 (rows 109..113).
        {
            runtime::AcrobatPoleRider rider;
            rider.state = runtime::kAcrobatPoleIdleState;
            rider.pole = rider.from = pole01;
            rider.clipTime = 20.0f;
            const auto afterRow = [&](int frame) {
                if (frame == 40) require(near(rider.verticalSpeed, 4.90156f, 2e-4f), "t1: ctrl+0x2e4 of the jump 02 -> 03");
                if (frame == 88) require(near(rider.verticalSpeed, -15.6937f, 1e-3f), "t1: ctrl+0x2e4 of the jump to the landing point");
                if (frame == 21 || frame == 38) require(rider.phase == (frame == 21 ? 1.0f : 2.0f), "t1: ctrl+0x24c");
                if (frame == 39) require(rider.pole == pole02, "t1: ctrl+0x130 on 02 in row 39");
            };
            replay(set, clips, rider, kT1, sizeof kT1 / sizeof kT1[0], 37.03597f, "t1", afterRow);
            require(!rider.active(), "t1: released to the fall in row 112");
        }
        // t2 from the end of the arrival (row 163, state 88 requests 93): 93 for 33 updates, 97 (no pole ahead facing -z), the fall in row 221.
        // The floor below is 30.6669 (t2 row 241).
        {
            runtime::AcrobatPoleRider rider;
            runtime::acrobatPoleStart(rider, pole01);
            const Row start[] = {{163, 88, 720.36835f, 41.45909f, 637.57922f, -0.21686f, -0.97620f, 2, 0, 0.40875f}};
            std::vector<Row> rows(start, start + 1);
            rows.insert(rows.end(), kT2, kT2 + sizeof kT2 / sizeof kT2[0]);
            replay(set, clips, rider, rows.data(), rows.size(), 30.6669f, "t2", {});
            require(!rider.active(), "t2: released to the fall in row 221");
        }
        // f1..f3 from row 2: idle on 01 facing +z (state 93), clip time 30 at the update of row 3: chosen so that the idle end falls in row 5, where f1 requests the
        // flip (stick 0x4000 against the camera: h in 0x2001..0x5fff, side -0.397). Flip rows 6..25, Flip Done in row 26 (93 facing -z), the idle end of row 58
        // keeps (stick to the same side), row 91 flips back, Flip Done in row 112 with B held jumps at once (95 with the grab's hang offset, then 96, 95).
        {
            runtime::AcrobatPoleRider rider;
            rider.state = runtime::kAcrobatPoleIdleState;
            rider.pole = rider.from = pole01;
            rider.clipTime = 30.0f;
            replay(set, clips, rider, kFlip, sizeof kFlip / sizeof kFlip[0], 30.6669f, "flip", {});
            require(rider.state == runtime::kAcrobatPoleJumpState, "flip: still jumping at the end of f3");
        }
        std::cout << "acrobat-pole-real-test: ok\n";
        return 0;
    } catch (const std::exception& error) {
        std::cerr << "acrobat-pole-real-test: " << error.what() << '\n';
        return 1;
    }
}
